<?php

declare(strict_types=1);

namespace StageArt\Application\Rehearsal;

use DateTimeImmutable;
use InvalidArgumentException;
use LogicException;
use RuntimeException;
use StageArt\Application\Production\ProductionNotFoundException;
use StageArt\Application\Shared\TransactionManagerInterface;
use StageArt\Core\Contract\AuthorizationContract;
use StageArt\Core\Contract\IdentityContract;
use StageArt\Core\Contract\MembershipContract;
use StageArt\Core\Contract\ProductionContextContract;
use StageArt\Domain\Person\PersonId;
use StageArt\Domain\Production\ProductionId;
use StageArt\Domain\Rehearsal\Rehearsal;
use StageArt\Domain\Rehearsal\RehearsalActivityType;
use StageArt\Domain\Rehearsal\RehearsalRepositoryInterface;
use StageArt\Domain\RehearsalAttendance\RehearsalAttendance;
use StageArt\Domain\RehearsalAttendance\RehearsalAttendanceRepositoryInterface;

/**
 * Generates Phase 1 (SCHEDULE_ADJUSTMENT) RehearsalAttendance records for
 * exactly the caller-supplied `targetPersonIds` (CreateRehearsalCommand),
 * not "every active Production member" - member selection at creation
 * time is a confirmed business requirement: an unselected Production
 * member is not an Attendance target for this Rehearsal. Each supplied
 * PersonId is validated against `MembershipContract::activeProductionMemberPersonIds()`
 * (still the authoritative "who is eligible to be selected" pool - this
 * does not relax who counts as a Production member, only who among them
 * is actually targeted) and rejected with InvalidArgumentException if it
 * names someone who is not an active, Person-subject Participant of this
 * Production. Phase 2 (ATTENDANCE_CONFIRMATION) records are explicitly
 * NOT created here; they are only ever generated by ConfirmRehearsalUseCase
 * at the SCHEDULED -> CONFIRMED transition.
 *
 * PR #7 R9 (§9.1): after the creation commits, every targeted member
 * receives the "planned" notification (RehearsalLifecycleNotifier). When
 * the response deadline is already within 24 hours at creation, the
 * reminder policy's immediate 【Remind】 is not sent on top of it - that
 * would be the same text twice at the same moment; the reminder is
 * marked sent instead, so it is not sent later either.
 *
 * PR #7 R9 (§5.2「確定」, §11): with `confirmOnCreate` the Rehearsal is
 * confirmed inside the same transaction (Rehearsal::confirm() plus the
 * Phase 2 records ConfirmRehearsalUseCase would create for the same
 * targets), no planning-stage reminder is scheduled, and the targets
 * receive only the §11 "confirmed" notification. Before R9 the screen
 * chained create + confirm as two requests, which would now announce
 * the same Rehearsal twice (planned, then confirmed).
 *
 * PR #7 R12 (docs/20-RehearsalManagementScreen.md §26): with an
 * idempotency key, a request sent again with the same key and the same
 * content (RehearsalCreateRequestHash) by the same person answers with the
 * Rehearsal the first one created - nothing is created and nobody is
 * notified again. The same key with different content, or from another
 * person, is a 409 (RehearsalIdempotencyConflictException). The key is
 * recorded first inside the creating transaction; a concurrent request
 * with the same key waits on the DB UNIQUE key, then gets the duplicate
 * error, rolls back everything it did and answers like a resend.
 *
 * StageArt Core/Module Architecture Phase 2: depends only on Core
 * Contracts (Identity/ProductionContext/Authorization/Membership), not
 * on `ProductionRepositoryInterface`/`ProductionAuthorizationService`/
 * `ParticipantRepositoryInterface` directly.
 */
final class CreateRehearsalUseCase
{
    private ProductionContextContract $productionContext;
    private RehearsalRepositoryInterface $rehearsals;
    private RehearsalAttendanceRepositoryInterface $attendances;
    private MembershipContract $membership;
    private RehearsalReminderDispatcher $reminderDispatcher;
    private RehearsalReminderSchedulerInterface $reminderScheduler;
    private IdentityContract $identity;
    private AuthorizationContract $authorization;
    private TransactionManagerInterface $transactions;
    private RehearsalLifecycleNotifier $lifecycleNotifier;
    private ?RehearsalCreateRequestStoreInterface $createRequests;

    public function __construct(
        ProductionContextContract $productionContext,
        RehearsalRepositoryInterface $rehearsals,
        RehearsalAttendanceRepositoryInterface $attendances,
        MembershipContract $membership,
        RehearsalReminderDispatcher $reminderDispatcher,
        RehearsalReminderSchedulerInterface $reminderScheduler,
        IdentityContract $identity,
        AuthorizationContract $authorization,
        TransactionManagerInterface $transactions,
        RehearsalLifecycleNotifier $lifecycleNotifier,
        ?RehearsalCreateRequestStoreInterface $createRequests = null
    ) {
        $this->productionContext = $productionContext;
        $this->rehearsals = $rehearsals;
        $this->attendances = $attendances;
        $this->membership = $membership;
        $this->reminderDispatcher = $reminderDispatcher;
        $this->reminderScheduler = $reminderScheduler;
        $this->identity = $identity;
        $this->authorization = $authorization;
        $this->transactions = $transactions;
        $this->lifecycleNotifier = $lifecycleNotifier;
        $this->createRequests = $createRequests;
    }

    public function execute(CreateRehearsalCommand $command): RehearsalResult
    {
        return $this->executeWithOutcome($command)->result;
    }

    public function executeWithOutcome(CreateRehearsalCommand $command): CreateRehearsalOutcome
    {
        $requesterId = $this->identity->resolveCurrentPersonId($command->requestedByWordPressUserId);

        if (! $requesterId) {
            throw new RehearsalAccessDeniedException('No StageArt Person is linked to this WordPress user.');
        }

        $productionId = ProductionId::fromString($command->productionId);
        $production = $this->productionContext->getProduction($productionId);

        if (! $production) {
            throw new ProductionNotFoundException($command->productionId);
        }

        if (! $this->authorization->canForProduction($requesterId, $productionId, RehearsalCapability::MANAGE)) {
            throw new RehearsalAccessDeniedException(
                'Only the PrimaryManager or a ProductionDelegate with the REHEARSAL_MANAGER Role can create Rehearsals.'
            );
        }

        // PR #7 R10 (§23.3): every date/time is read as an instant and held in
        // the Rehearsal's timezone (Asia/Tokyo unless one is given).
        $zone = RehearsalDateTime::zone($command->timezone);
        $startDateTime = RehearsalDateTime::parseRequired($command->startDateTime, $zone, 'start date/time');
        $endDateTime = RehearsalDateTime::parseRequired($command->endDateTime, $zone, 'end date/time');
        $responseDeadline = RehearsalDateTime::parseOptional($command->responseDeadline, $zone);
        $activityType = $this->parseOptionalActivityType($command->activityType);

        $idempotencyKey = self::idempotencyKey($command->idempotencyKey);
        $requestHash = null;

        if ($idempotencyKey !== null) {
            if ($this->createRequests === null) {
                throw new LogicException('CreateRehearsalUseCase was built without a RehearsalCreateRequestStoreInterface.');
            }

            $requestHash = RehearsalCreateRequestHash::hash(RehearsalCreateRequestHash::normalize(
                $productionId,
                $command->title,
                $command->description,
                $startDateTime,
                $endDateTime,
                $responseDeadline,
                $zone->getName(),
                $command->location,
                $command->targetPersonIds,
                $activityType,
                $command->confirmOnCreate
            ));

            // A resend is answered from what the first request created,
            // before re-checking the targets (they may have changed since).
            $existing = $this->createRequests->find($productionId, $idempotencyKey);

            if ($existing !== null) {
                return $this->replay($existing, $requesterId, $requestHash);
            }
        }

        $activeMemberIdStrings = array_map(
            static fn (PersonId $personId): string => $personId->toString(),
            $this->membership->activeProductionMemberPersonIds($productionId)
        );

        // A repeated id would otherwise hit UNIQUE(rehearsal_id, person_id,
        // phase) and be notified twice.
        $targetPersonIdStrings = array_values(array_unique($command->targetPersonIds));

        foreach ($targetPersonIdStrings as $targetPersonIdString) {
            if (! in_array($targetPersonIdString, $activeMemberIdStrings, true)) {
                throw new InvalidArgumentException(
                    "Person {$targetPersonIdString} is not an active Participant of this Production and cannot be selected as a Rehearsal Attendance target."
                );
            }
        }

        try {
            $rehearsal = $this->transactions->run(
                function () use ($productionId, $command, $targetPersonIdStrings, $startDateTime, $endDateTime, $responseDeadline, $activityType, $zone, $idempotencyKey, $requesterId, $requestHash): Rehearsal {
                    $rehearsal = Rehearsal::create(
                        $productionId,
                        $command->title,
                        $command->description,
                        $startDateTime,
                        $endDateTime,
                        $zone->getName(),
                        $command->location,
                        $responseDeadline,
                        $activityType
                    );

                    if ($idempotencyKey !== null) {
                        /** @var RehearsalCreateRequestStoreInterface $store checked above */
                        $store = $this->createRequests;
                        $store->record($productionId, $idempotencyKey, $requesterId, (string) $requestHash, $rehearsal->id());
                    }

                    return $this->createInTransaction($rehearsal, $command, $targetPersonIdStrings, $responseDeadline);
                }
            );
        } catch (RehearsalCreateRequestDuplicateException $duplicate) {
            // Another request with the same key committed first; this
            // transaction was rolled back. Answer like a resend.
            /** @var RehearsalCreateRequestStoreInterface $store */
            $store = $this->createRequests;
            $existing = $store->find($productionId, (string) $idempotencyKey);

            if ($existing === null) {
                throw new RuntimeException('The idempotency key was reported as recorded but cannot be read.', 0, $duplicate);
            }

            return $this->replay($existing, $requesterId, (string) $requestHash);
        }

        $targets = array_map(static fn (string $id): PersonId => PersonId::fromString($id), $targetPersonIdStrings);

        if ($command->confirmOnCreate) {
            $this->lifecycleNotifier->confirmed($rehearsal, $production->name, $targets);
        } else {
            $this->lifecycleNotifier->planned($rehearsal, $production->name, $targets);
        }

        return new CreateRehearsalOutcome(RehearsalResult::fromDomain($rehearsal), false);
    }

    /**
     * The writes of a new Rehearsal, inside the creating transaction.
     *
     * @param string[] $targetPersonIdStrings
     */
    private function createInTransaction(
        Rehearsal $rehearsal,
        CreateRehearsalCommand $command,
        array $targetPersonIdStrings,
        ?DateTimeImmutable $responseDeadline
    ): Rehearsal {
        $this->rehearsals->save($rehearsal);

        foreach ($targetPersonIdStrings as $targetPersonIdString) {
            $this->attendances->save(
                RehearsalAttendance::createPhase1($rehearsal->id(), PersonId::fromString($targetPersonIdString))
            );
        }

        if ($command->confirmOnCreate) {
            $rehearsal->confirm();
            $this->rehearsals->save($rehearsal);

            foreach ($targetPersonIdStrings as $targetPersonIdString) {
                $this->attendances->save(
                    RehearsalAttendance::createPhase2($rehearsal->id(), PersonId::fromString($targetPersonIdString))
                );
            }

            return $rehearsal;
        }

        $this->applyReminderPolicy($rehearsal, null, $responseDeadline, true);
        $this->rehearsals->save($rehearsal);

        return $rehearsal;
    }

    /**
     * PR #7 R12: the answer to a request whose key is already recorded.
     * Only the same person sending the same content gets the Rehearsal;
     * anything else is a conflict. Never creates or notifies.
     */
    private function replay(RehearsalCreateRequestRecord $existing, PersonId $requesterId, string $requestHash): CreateRehearsalOutcome
    {
        if (! $existing->requestedBy->equals($requesterId) || ! hash_equals($existing->requestHash, $requestHash)) {
            throw new RehearsalIdempotencyConflictException(
                'This idempotency key was already used for a different Rehearsal create request.'
            );
        }

        $rehearsal = $this->rehearsals->findById($existing->rehearsalId);

        if ($rehearsal === null) {
            throw new RuntimeException('The Rehearsal created for this idempotency key cannot be found.');
        }

        return new CreateRehearsalOutcome(RehearsalResult::fromDomain($rehearsal), true);
    }

    /**
     * 1-100 characters of letters, digits and "._:-" (a UUID fits).
     * Missing or empty: no idempotency. Anything else: 422.
     */
    private static function idempotencyKey(?string $value): ?string
    {
        if ($value === null || $value === '') {
            return null;
        }

        if (preg_match('/^[A-Za-z0-9._:-]{1,100}$/', $value) !== 1) {
            throw new InvalidArgumentException('Invalid idempotency_key: use 1-100 letters, digits, ".", "_", ":" or "-".');
        }

        return $value;
    }
    /**
     * StageArt 予定・活動一般化調査: null/empty defers to
     * Rehearsal::create()'s own default (REHEARSAL) - an invalid species
     * string is rejected the same way every other invalid Rehearsal
     * input is, as a 422.
     */
    private function parseOptionalActivityType(?string $value): ?RehearsalActivityType
    {
        if ($value === null || $value === '') {
            return null;
        }

        try {
            return RehearsalActivityType::fromString($value);
        } catch (InvalidArgumentException $exception) {
            throw new InvalidArgumentException("Invalid activity_type value: {$value}");
        }
    }
    /**
     * Phase 7: shared with `UpdateRehearsalUseCase` in spirit (not code -
     * each has its own copy since `$oldDeadline` is trivially `null` here,
     * always a "new deadline" or "no deadline" decision, never a genuine
     * change-direction one) - applies `RehearsalReminderPolicy`'s decision
     * for this Rehearsal's just-created deadline.
     */
    private function applyReminderPolicy(
        Rehearsal $rehearsal,
        ?DateTimeImmutable $oldDeadline,
        ?DateTimeImmutable $newDeadline,
        bool $plannedNotificationFollows = false
    ): void {
        $decision = RehearsalReminderPolicy::decideOnDeadlineChange($oldDeadline, $newDeadline, new DateTimeImmutable());

        switch ($decision['action']) {
            case RehearsalReminderPolicy::ACTION_SEND_NOW:
                if ($plannedNotificationFollows) {
                    // §9.1's notification goes out right after the commit
                    // with the same text minus 【Remind】 - count it as the
                    // reminder rather than sending both at once.
                    $rehearsal->markReminderSent(new DateTimeImmutable());
                    break;
                }

                $this->reminderDispatcher->dispatch($rehearsal);
                break;
            case RehearsalReminderPolicy::ACTION_SCHEDULE:
                $this->reminderScheduler->scheduleReminderAt($rehearsal->id(), $decision['reminderAt']);
                break;
            case RehearsalReminderPolicy::ACTION_CANCEL:
                $this->reminderScheduler->cancelReminder($rehearsal->id());
                break;
        }
    }
}
